"""Copy a pipeline run's lightweight outputs into the repository so they can be browsed on GitHub.

    python tools/snapshot_results.py --root ../run_v3 --label run_v3 [--log ../run_v3.log]

Copies results/*.json and results/*.md, figures/*.png and figures/*.pdf, writes a stage-status
manifest, and (optionally) a filtered run log without progress bars. Absolute paths are replaced by
<ROOT> / <REPO>. Large artefacts (datasets, model weights, grids, dynesty pickles) are never copied.
Safe to run while the pipeline is still running: it only reads the run directory.
"""
import argparse
import json
import re
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# Mirrors nseos.stages.ORDER without importing torch.
ORDER = ["simulate", "train", "evaluate", "grid", "realdata", "reference-real", "compare-real",
         "identifiability", "zero-noise", "ablate-arch", "ablate-messenger", "reference-synth",
         "importance", "convergence", "economics", "systematics", "summary"]

DESCRIBE = {
    "data_generation": "Simulation: attempts, acceptance, rejection reasons, simulator settings",
    "norm_stats": "Input normalisation statistics (log-sigma inputs)",
    "train_ensemble": "Main 3-seed ensemble: best epoch, epochs run, best validation loss, wall time",
    "eval_main": "Held-out test set: accuracy vs prior, by catalog size, coverage, TARP, symmetry and speed checks",
    "grid_validation": "Likelihood-grid interpolation error and support classification",
    "realdata": "Real catalog as parsed, out-of-distribution report, amortised posterior and derived quantities",
    "compare_real": "Real data: amortised vs dynesty (JS in bits with floors, C2ST, moments, derived, timing)",
    "identifiability": "Fisher / sensitivity analysis of the TOV map",
    "zero_noise": "Near-zero-noise model and model-free regressor (is gamma_2 / gamma_3 learnable at all?)",
    "ablation_arch": "Set Transformer vs DeepSets vs padded MLP, 3 seeds each",
    "ablation_messenger": "Contribution of each messenger (GW / NICER / radio)",
    "reference_synth": "Dynesty vs amortised posterior on synthetic catalogs",
    "importance": "Importance-sampling correction: efficiency, evidence, exact real-data posterior",
    "convergence": "Forward-model (TOV) discretisation error",
    "economics": "Offline cost, break-even number of analyses, subset workflow",
    "systematics": "Crust, noise-misreport and causality sensitivity",
    "summary": "All headline numbers in one file",
    "paper_numbers": "Paper-ready numbers (Markdown)",
    "timings": "Wall-clock timings recorded by a stage",
}


def _scrub(text, root):
    for path, tag in ((str(root), "<ROOT>"), (str(REPO), "<REPO>")):
        for form in (path, path.replace("\\", "/"), path.replace("\\", "\\\\")):
            text = text.replace(form, tag)
    text = re.sub(r"[A-Za-z]:\\\\?Users\\\\?[^\\\s\"']+", "<HOME>", text)
    return re.sub(r"/(home|Users)/[^/\s\"']+", "<HOME>", text)


def _kind(name):
    stem = name.rsplit(".", 1)[0]
    return re.sub(r"_sly4_[0-9a-f]{16}$", "", stem)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, help="pipeline --root directory")
    ap.add_argument("--label", required=True, help="folder name under results/")
    ap.add_argument("--log", default=None, help="pipeline --log file to include (progress bars removed)")
    a = ap.parse_args()
    root = Path(a.root).resolve()
    out = REPO / "results" / a.label
    if out.exists():
        shutil.rmtree(out)
    (out / "json").mkdir(parents=True)
    (out / "figures").mkdir()

    files = []
    for f in sorted((root / "results").glob("*")):
        if f.suffix in (".json", ".md"):
            (out / "json" / f.name).write_text(_scrub(f.read_text(encoding="utf-8"), root), encoding="utf-8")
            files.append(("json", f.name))
    for f in sorted((root / "figures").glob("*")):
        if f.suffix in (".png", ".pdf"):
            shutil.copy2(f, out / "figures" / f.name)
            files.append(("figures", f.name))

    done = {m.name.split("_sly4_")[0][len("stage_"):] for m in (root / "results").glob("stage_*.done")}
    running = None
    if a.log:
        log = Path(a.log).read_text(encoding="utf-8", errors="replace")
        started = re.findall(r"== stage: (\S+)", log)
        running = next((s for s in reversed(started) if s not in done), None)
        keep = []
        for line in log.splitlines():
            line = line.split("\r")[-1]
            if re.search(r"\d+/\d+ \[|it/s\]|s/it\]", line):
                continue
            keep.append(line)
        (out / "run_log.txt").write_text(_scrub("\n".join(keep) + "\n", root), encoding="utf-8")

    lines = [f"# Snapshot `{a.label}`", "",
             "Generated by `tools/snapshot_results.py` from the pipeline output directory. "
             "File names end in an input fingerprint (`_sly4_<hash>`); see `docs/CHANGES_v2.md`.", "",
             "## Stage status", "", "| # | stage | status |", "|---|---|---|"]
    for i, s in enumerate(ORDER, 1):
        status = "done" if s in done else ("**running**" if s == running else "pending")
        lines.append(f"| {i} | `{s}` | {status} |")
    lines += ["", "## Files", "", "| file | contents |", "|---|---|"]
    for sub, name in files:
        kind = _kind(name)
        desc = DESCRIBE.get(kind) or next((v for k, v in DESCRIBE.items() if kind.startswith(k)), "figure" if sub == "figures" else "")
        lines.append(f"| [`{sub}/{name}`]({sub}/{name}) | {desc} |")
    if a.log:
        lines += ["", "[`run_log.txt`](run_log.txt): the full pipeline log with progress bars removed."]
    (out / "MANIFEST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(files)} files to {out}; stages done: {len(done)}/{len(ORDER)}; running: {running}")


if __name__ == "__main__":
    main()
